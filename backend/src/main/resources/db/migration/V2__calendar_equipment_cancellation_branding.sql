-- Upgrade schema: Event Hall Calendar Schedule Blocks, Equipment Management,
-- Cancellation & Refund Management, Financial Audit Log, and University Branding.

CREATE TABLE IF NOT EXISTS hall_schedule_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hall_id BIGINT NOT NULL REFERENCES event_halls(id),
    block_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    block_type VARCHAR(40) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    created_by VARCHAR(60) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_schedule_hall_date ON hall_schedule_blocks(hall_id, block_date);

CREATE TABLE IF NOT EXISTS equipment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    category VARCHAR(60) NOT NULL,
    description VARCHAR(500),
    total_quantity INTEGER NOT NULL,
    unit_fee NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS equipment_reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES hall_applications(id),
    equipment_id BIGINT NOT NULL REFERENCES equipment(id),
    quantity_requested INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL,
    admin_comment VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_eq_res_app ON equipment_reservations(application_id);
CREATE INDEX IF NOT EXISTS idx_eq_res_eq ON equipment_reservations(equipment_id);

CREATE TABLE IF NOT EXISTS cancellation_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    full_refund_hours_before INTEGER NOT NULL DEFAULT 48,
    partial_refund_hours_before INTEGER NOT NULL DEFAULT 24,
    partial_refund_percent INTEGER NOT NULL DEFAULT 50,
    release_hall_on_approval BOOLEAN NOT NULL DEFAULT TRUE,
    description VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS cancellation_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL UNIQUE REFERENCES hall_applications(id),
    requested_by_id BIGINT NOT NULL REFERENCES users(id),
    reason VARCHAR(1000) NOT NULL,
    status VARCHAR(30) NOT NULL,
    refund_status VARCHAR(30) NOT NULL,
    paid_amount NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    eligible_refund_percent INTEGER NOT NULL DEFAULT 0,
    eligible_refund_amount NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    approved_refund_amount NUMERIC(12, 2),
    refund_transaction_ref VARCHAR(120),
    admin_comment VARCHAR(1000),
    processed_by VARCHAR(120),
    requested_at TIMESTAMP WITH TIME ZONE NOT NULL,
    processed_at TIMESTAMP WITH TIME ZONE,
    refund_completed_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_cancel_req_status ON cancellation_requests(status, refund_status);

CREATE TABLE IF NOT EXISTS financial_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT,
    application_code VARCHAR(40),
    cancellation_request_id BIGINT,
    actor_username VARCHAR(60) NOT NULL,
    actor_role VARCHAR(30) NOT NULL,
    action_type VARCHAR(60) NOT NULL,
    amount NUMERIC(12, 2),
    transaction_reference VARCHAR(120),
    details VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_fin_audit_created ON financial_audit_logs(created_at);

CREATE TABLE IF NOT EXISTS university_branding (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    university_name VARCHAR(160) NOT NULL,
    university_subtitle VARCHAR(200) NOT NULL,
    login_headline VARCHAR(200) NOT NULL,
    login_description VARCHAR(600) NOT NULL,
    primary_color VARCHAR(20) NOT NULL,
    secondary_color VARCHAR(20) NOT NULL,
    logo_filename VARCHAR(255),
    contact_email VARCHAR(120),
    contact_phone VARCHAR(40),
    contact_address VARCHAR(250),
    website_url VARCHAR(200),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
