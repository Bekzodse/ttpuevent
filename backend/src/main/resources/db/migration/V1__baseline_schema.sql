-- Baseline schema for UniPortal University Management System

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    phone_number VARCHAR(20) NOT NULL UNIQUE,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    profile_picture VARCHAR(255),
    department VARCHAR(120),
    bio VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_login_at TIMESTAMP WITH TIME ZONE,
    last_activity_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS login_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    login_time TIMESTAMP WITH TIME ZONE NOT NULL,
    ip_address VARCHAR(64),
    user_agent VARCHAR(255),
    successful BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS university_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    category VARCHAR(60) NOT NULL,
    event_date DATE NOT NULL,
    event_time VARCHAR(20) NOT NULL,
    location VARCHAR(150) NOT NULL,
    organizer VARCHAR(150) NOT NULL,
    capacity INTEGER NOT NULL,
    registered_count INTEGER NOT NULL DEFAULT 0,
    gradient VARCHAR(80) NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS event_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES university_events(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    registered_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_event_user UNIQUE (event_id, user_id)
);

CREATE TABLE IF NOT EXISTS event_halls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    building VARCHAR(120) NOT NULL,
    floor VARCHAR(40) NOT NULL,
    capacity INTEGER NOT NULL,
    hourly_rate NUMERIC(10, 2) NOT NULL,
    amenities VARCHAR(300),
    description VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS hall_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_code VARCHAR(40) NOT NULL UNIQUE,
    applicant_id BIGINT NOT NULL REFERENCES users(id),
    applicant_first_name VARCHAR(80) NOT NULL,
    applicant_last_name VARCHAR(80) NOT NULL,
    applicant_phone_number VARCHAR(20) NOT NULL,
    hall_id BIGINT NOT NULL REFERENCES event_halls(id),
    event_name VARCHAR(160) NOT NULL,
    event_type VARCHAR(60) NOT NULL,
    event_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    expected_participants INTEGER NOT NULL,
    description VARCHAR(2000),
    status VARCHAR(30) NOT NULL,
    payment_status VARCHAR(30),
    admin_comment VARCHAR(1000),
    user_reply VARCHAR(1500),
    required_amount NUMERIC(12, 2),
    bank_card_number VARCHAR(40),
    bank_card_holder VARCHAR(120),
    bank_name VARCHAR(120),
    receipt_filename VARCHAR(255),
    receipt_uploaded_at TIMESTAMP WITH TIME ZONE,
    approved_at TIMESTAMP WITH TIME ZONE,
    payment_deadline TIMESTAMP WITH TIME ZONE,
    payment_verified_at TIMESTAMP WITH TIME ZONE,
    verified_by_admin VARCHAR(120),
    confirmed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS application_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES hall_applications(id),
    actor_username VARCHAR(60) NOT NULL,
    actor_full_name VARCHAR(160) NOT NULL,
    actor_role VARCHAR(30) NOT NULL,
    action VARCHAR(60) NOT NULL,
    previous_status VARCHAR(30),
    new_status VARCHAR(30) NOT NULL,
    comment VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL REFERENCES users(id),
    title VARCHAR(160) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    type VARCHAR(20) NOT NULL,
    application_id BIGINT,
    application_code VARCHAR(40),
    booking_status VARCHAR(30),
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
