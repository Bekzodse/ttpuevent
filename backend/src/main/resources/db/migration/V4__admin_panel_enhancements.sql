-- Admin Panel Enhancement: User/Application email, Event image & publish state, and Admin Activity Logs

ALTER TABLE users ADD COLUMN IF NOT EXISTS email VARCHAR(160);

ALTER TABLE hall_applications ADD COLUMN IF NOT EXISTS applicant_email VARCHAR(160);

ALTER TABLE university_events ADD COLUMN IF NOT EXISTS image_url VARCHAR(500);
ALTER TABLE university_events ADD COLUMN IF NOT EXISTS published BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE IF NOT EXISTS admin_activity_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT,
    actor_username VARCHAR(60) NOT NULL,
    actor_full_name VARCHAR(160) NOT NULL,
    action_type VARCHAR(60) NOT NULL,
    target_type VARCHAR(40) NOT NULL,
    target_id BIGINT,
    target_label VARCHAR(200),
    details VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_admin_activity_created ON admin_activity_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_admin_activity_target ON admin_activity_logs(target_type, action_type);
